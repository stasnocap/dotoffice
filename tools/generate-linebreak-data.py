#!/usr/bin/env python3
"""Generates src/DotOffice.Layout/LineBreaking/LineBreakData.g.cs from Unicode's LineBreak.txt.

Usage: python3 tools/generate-linebreak-data.py [path/to/LineBreak.txt]
Without an argument the file is downloaded from unicode.org (version below).
"""
import os, re, sys, urllib.request

VERSION = "16.0.0"
URL = f"https://www.unicode.org/Public/{VERSION}/ucd/LineBreak.txt"

# Must match the LineBreakClass enum order.
CLASSES = ("XX BK CR LF CM NL SG WJ ZW GL SP ZWJ B2 BA BB HY CB CL CP EX IN NS OP QU IS NU PO PR SY "
           "AI AL CJ EB EM H2 H3 HL ID JL JV JT RI SA AK AP AS VF VI").split()

def main():
    if len(sys.argv) > 1:
        text = open(sys.argv[1], encoding="utf-8").read()
    else:
        text = urllib.request.urlopen(URL).read().decode("utf-8")
    header = text.splitlines()[0].lstrip("# ").strip()
    classes = bytearray(0x110000)  # default XX
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cps, cls = [p.strip() for p in line.split(";")]
        lo, _, hi = cps.partition("..")
        lo = int(lo, 16); hi = int(hi or cps, 16)
        value = CLASSES.index(cls)
        classes[lo:hi + 1] = bytes([value]) * (hi - lo + 1)

    starts, values = [], []
    for cp in range(0x110000):
        if not values or classes[cp] != values[-1]:
            starts.append(cp); values.append(classes[cp])

    out = os.path.join(os.path.dirname(__file__), "..", "src", "DotOffice.Layout", "LineBreaking", "LineBreakData.g.cs")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// <auto-generated>\n")
        f.write(f"// Generated by tools/generate-linebreak-data.py from {header}.\n")
        f.write("// Unicode Character Database: Copyright (c) 1991-2024 Unicode, Inc.\n")
        f.write("// Distributed under the Unicode License v3; see THIRD-PARTY-NOTICES.md.\n")
        f.write("// </auto-generated>\n\nnamespace DotOffice.Layout.LineBreaking;\n\n")
        f.write("internal static class LineBreakData\n{\n")
        f.write(f"    public const string UnicodeVersion = \"{VERSION}\";\n\n")
        f.write("    /// <summary>First code point of each range; a range extends to the next start.</summary>\n")
        f.write("    public static ReadOnlySpan<int> RangeStarts => new int[]\n    {\n")
        for i in range(0, len(starts), 12):
            f.write("        " + ", ".join(f"0x{s:X}" for s in starts[i:i + 12]) + ",\n")
        f.write("    };\n\n")
        f.write("    /// <summary>LineBreakClass of each range.</summary>\n")
        f.write("    public static ReadOnlySpan<byte> RangeClasses =>\n    [\n")
        for i in range(0, len(values), 24):
            f.write("        " + ", ".join(str(v) for v in values[i:i + 24]) + ",\n")
        f.write("    ];\n}\n")
    print(f"{len(starts)} ranges written to {os.path.normpath(out)}")

if __name__ == "__main__":
    main()
