#!/usr/bin/env python3
"""Generates the Unicode tables used for bidirectional text and Arabic shaping:

  src/DotOffice.Layout/Bidi/BidiData.g.cs      bidi classes, mirroring pairs, paired brackets (UAX #9)
  src/DotOffice.Fonts/Shaping/JoiningData.g.cs Arabic joining types (ArabicShaping.txt) and canonical
                                               combining classes (UnicodeData.txt) for mark reordering

Usage: python3 tools/generate-bidi-data.py [directory containing the UCD files]
Without an argument the files are downloaded from unicode.org (version below).
"""
import os, sys, urllib.request

VERSION = "16.0.0"
BASE = f"https://www.unicode.org/Public/{VERSION}/ucd/"
FILES = {
    "DerivedBidiClass.txt": "extracted/DerivedBidiClass.txt",
    "BidiMirroring.txt": "BidiMirroring.txt",
    "BidiBrackets.txt": "BidiBrackets.txt",
    "ArabicShaping.txt": "ArabicShaping.txt",
    "UnicodeData.txt": "UnicodeData.txt",
}

# Must match the BidiClass enum order.
BIDI_CLASSES = "L R AL EN ES ET AN CS NSM BN B S WS ON LRE LRO RLE RLO PDF LRI RLI FSI PDI".split()
# Must match the JoiningType enum order; 0 means "not listed" (derived from the general category at run time).
JOINING_TYPES = "X U R L D C T".split()

ROOT = os.path.join(os.path.dirname(__file__), "..")
HEADER = ("// <auto-generated>\n"
          "// Generated by tools/generate-bidi-data.py from the Unicode Character Database {version}.\n"
          "// Unicode Character Database: Copyright (c) 1991-2024 Unicode, Inc.\n"
          "// Distributed under the Unicode License v3; see THIRD-PARTY-NOTICES.md.\n"
          "// </auto-generated>\n\n")


def load(name):
    if len(sys.argv) > 1:
        return open(os.path.join(sys.argv[1], name), encoding="utf-8").read()
    return urllib.request.urlopen(BASE + FILES[name]).read().decode("utf-8")


def records(text):
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            yield [p.strip() for p in line.split(";")]


def code_range(field):
    lo, _, hi = field.partition("..")
    return int(lo, 16), int(hi or lo, 16)


def ranges(values):
    starts, out = [], []
    for cp, value in enumerate(values):
        if not out or value != out[-1]:
            starts.append(cp)
            out.append(value)
    return starts, out


def write_ranges(f, starts, values, value_doc):
    f.write("    /// <summary>First code point of each range; a range extends to the next start.</summary>\n")
    f.write("    public static ReadOnlySpan<int> RangeStarts => new int[]\n    {\n")
    for i in range(0, len(starts), 12):
        f.write("        " + ", ".join(f"0x{s:X}" for s in starts[i:i + 12]) + ",\n")
    f.write("    };\n\n")
    f.write(f"    /// <summary>{value_doc}</summary>\n")
    f.write("    public static ReadOnlySpan<byte> RangeValues =>\n    [\n")
    for i in range(0, len(values), 24):
        f.write("        " + ", ".join(str(v) for v in values[i:i + 24]) + ",\n")
    f.write("    ];\n")


def main():
    # Unassigned code points take block defaults from the "# @missing:" lines (long value names).
    long_names = {"Left_To_Right": "L", "Right_To_Left": "R", "Arabic_Letter": "AL", "European_Terminator": "ET",
                  "Boundary_Neutral": "BN"}
    bidi = bytearray(0x110000)
    derived = load("DerivedBidiClass.txt")
    for line in derived.splitlines():
        if line.startswith("# @missing:"):
            cps, cls = [p.strip() for p in line[len("# @missing:"):].split(";")]
            lo, hi = code_range(cps)
            bidi[lo:hi + 1] = bytes([BIDI_CLASSES.index(long_names[cls])]) * (hi - lo + 1)
    for cps, cls in records(derived):
        lo, hi = code_range(cps)
        bidi[lo:hi + 1] = bytes([BIDI_CLASSES.index(cls)]) * (hi - lo + 1)

    mirrors = sorted((int(a, 16), int(b, 16)) for a, b in records(load("BidiMirroring.txt")))
    brackets = sorted((int(a, 16), int(b, 16), t) for a, b, t in records(load("BidiBrackets.txt")))

    joining = bytearray(0x110000)
    for fields in records(load("ArabicShaping.txt")):
        cp, jt = int(fields[0], 16), fields[2]
        joining[cp] = JOINING_TYPES.index(jt)

    combining = bytearray(0x110000)
    first = None
    for fields in records(load("UnicodeData.txt")):
        cp, name, ccc = int(fields[0], 16), fields[1], int(fields[3])
        if name.endswith(", First>"):
            first = cp
            continue
        lo = first if name.endswith(", Last>") else cp
        combining[lo:cp + 1] = bytes([ccc]) * (cp - lo + 1)
        first = None

    path = os.path.join(ROOT, "src", "DotOffice.Layout", "Bidi", "BidiData.g.cs")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    starts, values = ranges(bidi)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER.format(version=VERSION))
        f.write("namespace DotOffice.Layout.Bidi;\n\ninternal static class BidiData\n{\n")
        f.write(f"    public const string UnicodeVersion = \"{VERSION}\";\n\n")
        write_ranges(f, starts, values, "BidiClass of each range.")
        f.write("\n    /// <summary>Bidi_Mirroring_Glyph pairs, sorted by the first code point.</summary>\n")
        f.write("    public static ReadOnlySpan<int> Mirrors => new int[]\n    {\n")
        for i in range(0, len(mirrors), 6):
            f.write("        " + " ".join(f"0x{a:X}, 0x{b:X}," for a, b in mirrors[i:i + 6]) + "\n")
        f.write("    };\n\n")
        f.write("    /// <summary>Paired brackets (code point, paired bracket, 1 = opening / 0 = closing), sorted.</summary>\n")
        f.write("    public static ReadOnlySpan<int> Brackets => new int[]\n    {\n")
        for i in range(0, len(brackets), 6):
            f.write("        " + " ".join(f"0x{a:X}, 0x{b:X}, {1 if t == 'o' else 0}," for a, b, t in brackets[i:i + 6]) + "\n")
        f.write("    };\n}\n")
    print(f"{len(starts)} bidi ranges, {len(mirrors)} mirrors, {len(brackets)} brackets written to {os.path.normpath(path)}")

    path = os.path.join(ROOT, "src", "DotOffice.Fonts", "Shaping", "JoiningData.g.cs")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    starts, values = ranges(joining)
    ccc_starts, ccc_values = ranges(combining)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER.format(version=VERSION))
        f.write("namespace DotOffice.Fonts.Shaping;\n\ninternal static class JoiningData\n{\n")
        write_ranges(f, starts, values, "JoiningType of each range (0 = not listed in ArabicShaping.txt).")
        f.write("}\n\ninternal static class CombiningClassData\n{\n")
        write_ranges(f, ccc_starts, ccc_values, "Canonical_Combining_Class of each range.")
        f.write("}\n")
    print(f"{len(starts)} joining ranges, {len(ccc_starts)} combining class ranges written to {os.path.normpath(path)}")


if __name__ == "__main__":
    main()
