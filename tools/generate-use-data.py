#!/usr/bin/env python3
"""Generates the Unicode table used by the Universal Shaping Engine shaper:

  src/DotOffice.Fonts/Shaping/UseData.g.cs  USE category of each character, a port of the classification in
                                            HarfBuzz's gen-use-table.py (MIT license, see THIRD-PARTY-NOTICES.md)

Only characters of the scripts DotOffice shapes with USE (Sinhala, Tibetan) and of the Common and Inherited scripts
(spaces, digits, joiners, variation selectors, ...) are included; everything else is category O. The Microsoft
"-Additional" property files that HarfBuzz merges in only concern scripts outside that set.

The two ms-use/*-Additional.txt files come from HarfBuzz's src/ms-use directory (same directory as the UCD files
when an argument is given).

Usage: python3 tools/generate-use-data.py [directory containing the UCD files]
Without an argument the files are downloaded from unicode.org (version below).
"""
import os, sys, urllib.request

VERSION = "16.0.0"
BASE = f"https://www.unicode.org/Public/{VERSION}/ucd/"
FILES = ["IndicSyllabicCategory.txt", "IndicPositionalCategory.txt", "ArabicShaping.txt",
         "DerivedCoreProperties.txt", "UnicodeData.txt", "Scripts.txt"]
SCRIPTS = {"Sinhala", "Tibetan", "Common", "Inherited"}

# Numbers from the "export" lines of hb-ot-shaper-use-machine.rl.
CATEGORY = {
    "O": 0, "B": 1, "N": 4, "GB": 5, "CGJ": 6, "SUB": 11, "H": 12, "HN": 13, "ZWNJ": 14, "WJ": 16, "R": 18,
    "CS": 43, "IS": 44, "Sk": 48, "G": 49, "J": 50, "SB": 51, "SE": 52, "HVM": 53, "HM": 54, "HR": 55, "RK": 56,
    "FAbv": 24, "FBlw": 25, "FPst": 26, "MAbv": 27, "MBlw": 28, "MPst": 29, "MPre": 30, "CMAbv": 31,
    "CMBlw": 32, "VAbv": 33, "VBlw": 34, "VPst": 35, "VPre": 22, "VMAbv": 37, "VMBlw": 38, "VMPst": 39,
    "VMPre": 23, "SMAbv": 41, "SMBlw": 42, "FMAbv": 45, "FMBlw": 46, "FMPst": 47,
}

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
HEADER = ("// <auto-generated>\n"
          "// Generated by tools/generate-use-data.py from the Unicode Character Database {version},\n"
          "// following HarfBuzz's gen-use-table.py.\n"
          "// Unicode Character Database: Copyright (c) 1991-2024 Unicode, Inc.\n"
          "// Distributed under the Unicode License v3; HarfBuzz under the MIT license; see THIRD-PARTY-NOTICES.md.\n"
          "// </auto-generated>\n\n")


ADDITIONAL = ["IndicSyllabicCategory-Additional.txt", "IndicPositionalCategory-Additional.txt"]
ADDITIONAL_BASE = "https://raw.githubusercontent.com/harfbuzz/harfbuzz/main/src/ms-use/"


def load(name):
    if len(sys.argv) > 1:
        return open(os.path.join(sys.argv[1], name), encoding="utf-8").read()
    return urllib.request.urlopen((ADDITIONAL_BASE if name in ADDITIONAL else BASE) + name).read().decode("utf-8")


def ranges(text, field=1):
    for line in text.splitlines():
        line = line.split("#")[0]
        fields = [f.strip() for f in line.split(";")]
        if len(fields) <= field:
            continue
        a, _, b = fields[0].partition("..")
        for u in range(int(a, 16), int(b or a, 16) + 1):
            yield u, fields[field]


def is_base(u, isc, di, gc, jt):
    return (isc in ("Number", "Consonant", "Consonant_Head_Letter", "Tone_Letter", "Vowel_Independent")
            or (jt in ("C", "D", "L", "R") and isc != "Joiner")
            or (gc == "Lo" and isc in ("Avagraha", "Bindu", "Consonant_Final", "Consonant_Medial",
                                       "Consonant_Subjoined", "Vowel", "Vowel_Dependent")))


def is_base_other(u, isc, di, gc, jt):
    return isc == "Consonant_Placeholder" or u in (0x2015, 0x2022, 0x25FB, 0x25FC, 0x25FD, 0x25FE)


def is_cgj(u, isc, di, gc, jt):  # also variation selectors and ZWJ
    return isc == "Joiner" or (di and gc in ("Mc", "Me", "Mn"))


def is_sym_mod(u, isc, di, gc, jt):
    return isc == "Symbol_Modifier"


def is_word_joiner(u, isc, di, gc, jt):  # also reserved
    return (di and u not in (0x115F, 0x1160, 0x3164, 0xFFA0, 0x1BCA0, 0x1BCA1, 0x1BCA2, 0x1BCA3)
            and isc == "Other" and not is_cgj(u, isc, di, gc, jt)) or gc == "Cn"


def is_hvm(u, isc, di, gc, jt):
    return u == 0x0DCA


def is_sakot(u, isc, di, gc, jt):
    return u == 0x1A60


def is_other(u, isc, di, gc, jt):
    return ((gc == "Po" or isc in ("Consonant_Dead", "Joiner", "Modifying_Letter", "Other"))
            and not is_base(u, isc, di, gc, jt) and not is_base_other(u, isc, di, gc, jt)
            and not is_cgj(u, isc, di, gc, jt) and not is_sym_mod(u, isc, di, gc, jt)
            and not is_word_joiner(u, isc, di, gc, jt))


MAPPING = {
    "B": is_base,
    "N": lambda u, isc, di, gc, jt: isc == "Brahmi_Joining_Number",
    "GB": is_base_other,
    "CGJ": is_cgj,
    "F": lambda u, isc, di, gc, jt: (isc == "Consonant_Final" and gc != "Lo") or isc == "Consonant_Succeeding_Repha",
    "FM": lambda u, isc, di, gc, jt: isc == "Syllable_Modifier",
    "M": lambda u, isc, di, gc, jt: (isc == "Consonant_Medial" and gc != "Lo") or isc == "Consonant_Initial_Postfixed",
    "CM": lambda u, isc, di, gc, jt: isc in ("Nukta", "Gemination_Mark", "Consonant_Killer"),
    "SUB": lambda u, isc, di, gc, jt: isc == "Consonant_Subjoined" and gc != "Lo",
    "CS": lambda u, isc, di, gc, jt: isc == "Consonant_With_Stacker",
    "H": lambda u, isc, di, gc, jt: isc == "Virama" and not is_hvm(u, isc, di, gc, jt),
    "HVM": is_hvm,
    "HN": lambda u, isc, di, gc, jt: isc == "Number_Joiner",
    "IS": lambda u, isc, di, gc, jt: isc == "Invisible_Stacker" and not is_sakot(u, isc, di, gc, jt),
    "G": lambda u, isc, di, gc, jt: isc == "Hieroglyph",
    "HM": lambda u, isc, di, gc, jt: isc == "Hieroglyph_Modifier",
    "HR": lambda u, isc, di, gc, jt: isc == "Hieroglyph_Mirror",
    "J": lambda u, isc, di, gc, jt: isc == "Hieroglyph_Joiner",
    "SB": lambda u, isc, di, gc, jt: isc in ("Hieroglyph_Mark_Begin", "Hieroglyph_Segment_Begin"),
    "SE": lambda u, isc, di, gc, jt: isc in ("Hieroglyph_Mark_End", "Hieroglyph_Segment_End"),
    "ZWNJ": lambda u, isc, di, gc, jt: isc == "Non_Joiner",
    "O": is_other,
    "RK": lambda u, isc, di, gc, jt: isc == "Reordering_Killer",
    "R": lambda u, isc, di, gc, jt: isc in ("Consonant_Preceding_Repha", "Consonant_Prefixed"),
    "Sk": is_sakot,
    "SM": is_sym_mod,
    "V": lambda u, isc, di, gc, jt: isc == "Pure_Killer" or (gc != "Lo" and isc in ("Vowel", "Vowel_Dependent")),
    "VM": lambda u, isc, di, gc, jt: isc in ("Tone_Mark", "Cantillation_Mark", "Register_Shifter", "Visarga")
                                      or (gc != "Lo" and isc == "Bindu"),
    "WJ": is_word_joiner,
}

POSITIONS = {
    "F": {"Abv": ["Top"], "Blw": ["Bottom"], "Pst": ["Right"]},
    "M": {"Abv": ["Top"], "Blw": ["Bottom", "Bottom_And_Left", "Bottom_And_Right"], "Pst": ["Right"],
          "Pre": ["Left", "Top_And_Bottom_And_Left"]},
    "CM": {"Abv": ["Top"], "Blw": ["Bottom", "Overstruck"]},
    "V": {"Abv": ["Top", "Top_And_Bottom", "Top_And_Bottom_And_Right", "Top_And_Right"],
          "Blw": ["Bottom", "Overstruck", "Bottom_And_Right"], "Pst": ["Right"],
          "Pre": ["Left", "Top_And_Left", "Top_And_Left_And_Right", "Left_And_Right"]},
    "VM": {"Abv": ["Top"], "Blw": ["Bottom", "Overstruck"], "Pst": ["Right"], "Pre": ["Left"]},
    "SM": {"Abv": ["Top"], "Blw": ["Bottom"]},
    "FM": {"Abv": ["Top"], "Blw": ["Bottom"], "Pst": ["Not_Applicable"]},
}


def main():
    isc_all = dict(ranges(load("IndicSyllabicCategory.txt")))
    ipc_all = dict(ranges(load("IndicPositionalCategory.txt")))
    # Microsoft's USE development spec overrides some properties (Tibetan above all); HarfBuzz merges them last.
    isc_all.update(ranges(load(ADDITIONAL[0])))
    ipc_all.update(ranges(load(ADDITIONAL[1])))
    jt_all = {}
    for line in load("ArabicShaping.txt").splitlines():
        line = line.split("#")[0]
        f = [x.strip() for x in line.split(";")]
        if len(f) >= 3 and f[0]:
            jt_all[int(f[0], 16)] = f[2]
    di = {u for u, t in ranges(load("DerivedCoreProperties.txt")) if t == "Default_Ignorable_Code_Point"}
    gc = {}
    for line in load("UnicodeData.txt").splitlines():
        f = line.split(";")
        gc[int(f[0], 16)] = f[2]
    script = dict(ranges(load("Scripts.txt")))

    data = {}
    for u in set(isc_all) | set(ipc_all) | set(jt_all) | di:
        if script.get(u) not in SCRIPTS:
            continue
        isc, ipc, jt = isc_all.get(u, "Other"), ipc_all.get(u, "NA"), jt_all.get(u, "X")
        if ipc == "NA":
            ipc = "Not_Applicable"
        if isc == "Consonant_Final_Modifier":
            isc = "Syllable_Modifier"
        if 0x1CE2 <= u <= 0x1CE8:  # no UISC in Unicode 13, but a UIPC (as HarfBuzz)
            isc = "Cantillation_Mark"
        if u == 0x1CED:
            isc = "Tone_Mark"
        if 0x0F18 <= u <= 0x0F19 or 0x0F3E <= u <= 0x0F3F:  # Tibetan: UIPC but no UISC in Unicode 13
            isc = "Vowel_Dependent"
        g = gc.get(u, "Cn")
        found = [k for k, v in MAPPING.items() if v(u, isc, u in di, g, jt)]
        assert len(found) == 1, (hex(u), isc, ipc, g, jt, found)
        cat = found[0]
        mapping = POSITIONS.get(cat)
        if mapping:
            if cat in ("F", "M", "CM", "V", "VM", "SM", "FM"):
                options = [k for k, v in mapping.items() if ipc in v]
                if not options:
                    # HarfBuzz asserts here except for these; U+0F7F is the one real exception.
                    assert ipc in ("Not_Applicable", "Visual_Order_Left") or u == 0x0F7F, (hex(u), cat, ipc)
                    options = ["Pst"] if u == 0x0F7F else None
                    if options is None:
                        continue
                cat += options[0]
        elif ipc not in ("Not_Applicable", "Visual_Order_Left") and cat not in (
                "H", "HM", "HR", "HVM", "IS", "B", "R", "RK", "SUB"):
            # HarfBuzz asserts here; its Microsoft "-Additional" files give such characters a syllabic category.
            print(f"note: U+{u:04X} {cat} with positional category {ipc} stays {cat}", file=sys.stderr)
        data[u] = cat

    starts, values, previous = [], [], None
    for u in range(0, max(data) + 2):
        value = CATEGORY[data.get(u, "O")]
        if value != previous:
            starts.append(u)
            values.append(value)
            previous = value

    out = [HEADER.format(version=VERSION), "namespace DotOffice.Fonts.Shaping;\n\n",
           "internal static class UseData\n{\n",
           "    /// <summary>First code point of each range; a range extends to the next start.</summary>\n",
           "    public static ReadOnlySpan<int> RangeStarts => new int[]\n    {\n"]
    out += wrap([f"0x{u:X}" for u in starts])
    out += ["    };\n\n",
            "    /// <summary>Per range: the <see cref=\"UseCategory\"/>.</summary>\n",
            "    public static ReadOnlySpan<byte> RangeValues => new byte[]\n    {\n"]
    out += wrap([str(v) for v in values])
    out += ["    };\n}\n"]
    path = os.path.join(ROOT, "src/DotOffice.Fonts/Shaping/UseData.g.cs")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(out))
    print(f"wrote {path}: {len(starts)} ranges, {len(data)} characters")


def wrap(items, per_line=12):
    return ["        " + ", ".join(items[i:i + per_line]) + ",\n" for i in range(0, len(items), per_line)]


if __name__ == "__main__":
    main()
