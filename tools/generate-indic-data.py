#!/usr/bin/env python3
"""Generates the Unicode tables used by the Indic shaper:

  src/DotOffice.Fonts/Shaping/IndicData.g.cs  shaping category and position of each character (as in
                                              HarfBuzz's gen-indic-table.py)

Usage: python3 tools/generate-indic-data.py [directory containing the UCD files]
Without an argument the files are downloaded from unicode.org (version below).
"""
import os, sys, urllib.request

VERSION = "16.0.0"
BASE = f"https://www.unicode.org/Public/{VERSION}/ucd/"
FILES = {
    "IndicSyllabicCategory.txt": "IndicSyllabicCategory.txt",
    "IndicPositionalCategory.txt": "IndicPositionalCategory.txt",
    "Blocks.txt": "Blocks.txt",
}

# Must match the IndicCategory enum order (HarfBuzz's indic_syllable_machine categories; VD is the same as A).
CATEGORIES = "X C V N H ZWNJ ZWJ M SM A PLACEHOLDER DOTTEDCIRCLE RS MPst Repha Ra CM Symbol CS SMPst".split()
# Must match the IndicPosition enum order (HarfBuzz's ot_position_t).
POSITIONS = ("START RA_TO_BECOME_REPH PRE_M PRE_C BASE_C AFTER_MAIN ABOVE_C BEFORE_SUB BELOW_C AFTER_SUB "
             "BEFORE_POST POST_C AFTER_POST SMVD END").split()

ALLOWED_SINGLES = [0x00A0, 0x25CC]
ALLOWED_BLOCKS = ["Basic Latin", "Latin-1 Supplement", "Devanagari", "Bengali", "Gurmukhi", "Gujarati", "Oriya",
                  "Tamil", "Telugu", "Kannada", "Malayalam", "Vedic Extensions", "General Punctuation",
                  "Superscripts and Subscripts", "Devanagari Extended"]

ROOT = os.path.join(os.path.dirname(__file__), "..")
HEADER = ("// <auto-generated>\n"
          "// Generated by tools/generate-indic-data.py from the Unicode Character Database {version},\n"
          "// following HarfBuzz's gen-indic-table.py.\n"
          "// Unicode Character Database: Copyright (c) 1991-2024 Unicode, Inc.\n"
          "// Distributed under the Unicode License v3; HarfBuzz under the MIT license; see THIRD-PARTY-NOTICES.md.\n"
          "// </auto-generated>\n\n")

CATEGORY_MAP = {
    "Other": "X", "Avagraha": "Symbol", "Bindu": "SM", "Brahmi_Joining_Number": "PLACEHOLDER",
    "Cantillation_Mark": "A", "Consonant": "C", "Consonant_Dead": "C", "Consonant_Final": "CM",
    "Consonant_Head_Letter": "C", "Consonant_Initial_Postfixed": "C", "Consonant_Killer": "M",
    "Consonant_Medial": "CM", "Consonant_Placeholder": "PLACEHOLDER", "Consonant_Preceding_Repha": "Repha",
    "Consonant_Prefixed": "X", "Consonant_Subjoined": "CM", "Consonant_Succeeding_Repha": "CM",
    "Consonant_With_Stacker": "CS", "Gemination_Mark": "SM", "Invisible_Stacker": "H", "Joiner": "ZWJ",
    "Modifying_Letter": "X", "Non_Joiner": "ZWNJ", "Nukta": "N", "Number": "PLACEHOLDER",
    "Number_Joiner": "PLACEHOLDER", "Pure_Killer": "M", "Register_Shifter": "RS", "Syllable_Modifier": "SM",
    "Tone_Letter": "X", "Tone_Mark": "N", "Virama": "H", "Visarga": "SM", "Vowel": "V",
    "Vowel_Dependent": "M", "Vowel_Independent": "V",
}
POSITION_MAP = {
    "Not_Applicable": "END", "Left": "PRE_C", "Top": "ABOVE_C", "Bottom": "BELOW_C", "Right": "POST_C",
    "Bottom_And_Right": "POST_C", "Left_And_Right": "POST_C", "Top_And_Bottom": "BELOW_C",
    "Top_And_Bottom_And_Left": "BELOW_C", "Top_And_Bottom_And_Right": "POST_C", "Top_And_Left": "ABOVE_C",
    "Top_And_Left_And_Right": "POST_C", "Top_And_Right": "POST_C", "Overstruck": "AFTER_MAIN",
    "Visual_order_left": "PRE_M",
}
CATEGORY_OVERRIDES = {
    0x2015: "PLACEHOLDER", 0x2022: "PLACEHOLDER", 0x25FB: "PLACEHOLDER", 0x25FC: "PLACEHOLDER",
    0x25FD: "PLACEHOLDER", 0x25FE: "PLACEHOLDER",
    0x0930: "Ra", 0x09B0: "Ra", 0x09F0: "Ra", 0x0A30: "Ra", 0x0AB0: "Ra", 0x0B30: "Ra", 0x0BB0: "Ra",
    0x0C30: "Ra", 0x0CB0: "Ra", 0x0D30: "Ra",
    0x0953: "SM", 0x0954: "SM", 0x0A40: "MPst", 0x0A72: "C", 0x0A73: "C",
    **{u: "A" for u in range(0x1CE2, 0x1CE9)}, 0x1CED: "A",
    **{u: "Symbol" for u in [*range(0xA8F2, 0xA8F8), *range(0x1CE9, 0x1CED), *range(0x1CEE, 0x1CF2)]},
    0x0A51: "M", 0x11301: "SM", 0x11302: "SM", 0x11303: "SM", 0x1133B: "N", 0x1133C: "N",
    0x0AFB: "N", 0x0B55: "N", 0x09FC: "PLACEHOLDER", 0x0C80: "PLACEHOLDER", 0x0D04: "PLACEHOLDER",
    0x25CC: "DOTTEDCIRCLE",
}
POSITION_OVERRIDES = {0x0A51: "BELOW_C", 0x0B01: "BEFORE_SUB"}


def matra_position(u, pos, block):
    if pos == "PRE_C":
        return "PRE_M"
    if pos == "POST_C":
        return {"Devanagari": "AFTER_SUB", "Bengali": "AFTER_POST", "Gurmukhi": "AFTER_POST", "Gujarati": "AFTER_POST",
                "Oriya": "AFTER_POST", "Tamil": "AFTER_POST", "Malayalam": "AFTER_POST",
                "Telugu": "BEFORE_SUB" if u <= 0x0C42 else "AFTER_SUB",
                "Kannada": "BEFORE_SUB" if u < 0x0CC3 or u > 0x0CD6 else "AFTER_SUB"}.get(block, "AFTER_SUB")
    if pos == "ABOVE_C":
        return {"Devanagari": "AFTER_SUB", "Gurmukhi": "AFTER_POST", "Gujarati": "AFTER_SUB", "Oriya": "AFTER_MAIN",
                "Tamil": "AFTER_SUB", "Telugu": "BEFORE_SUB", "Kannada": "BEFORE_SUB"}.get(block, "AFTER_SUB")
    if pos == "BELOW_C":
        return {"Devanagari": "AFTER_SUB", "Bengali": "AFTER_SUB", "Gurmukhi": "AFTER_POST", "Gujarati": "AFTER_POST",
                "Oriya": "AFTER_SUB", "Tamil": "AFTER_POST", "Telugu": "BEFORE_SUB", "Kannada": "BEFORE_SUB",
                "Malayalam": "AFTER_POST"}.get(block, "AFTER_SUB")
    raise ValueError(pos)


def load(name):
    if len(sys.argv) > 1:
        return open(os.path.join(sys.argv[1], name), encoding="utf-8").read()
    return urllib.request.urlopen(BASE + FILES[name]).read().decode("utf-8")


def ranges(text):
    for line in text.splitlines():
        line = line.split("#")[0]
        fields = [f.strip() for f in line.split(";")]
        if len(fields) < 2:
            continue
        a, _, b = fields[0].partition("..")
        for u in range(int(a, 16), int(b or a, 16) + 1):
            yield u, fields[1]


def main():
    syllabic = dict(ranges(load("IndicSyllabicCategory.txt")))
    positional = dict(ranges(load("IndicPositionalCategory.txt")))
    blocks = dict(ranges(load("Blocks.txt")))

    data = {}
    for u in set(syllabic) | set(positional):
        block = blocks.get(u, "No_Block")
        if u not in ALLOWED_SINGLES and block not in ALLOWED_BLOCKS:
            continue
        cat = CATEGORY_MAP[syllabic.get(u, "Other")]
        pos = positional.get(u, "Not_Applicable")
        if cat == "SM" and pos == "Not_Applicable":
            cat = "SMPst"
        data[u] = [cat, POSITION_MAP[pos], block]
    for u, cat in CATEGORY_OVERRIDES.items():
        entry = data.get(u, ["X", "END", blocks.get(u, "No_Block")])
        data[u] = [cat, entry[1], blocks.get(u, "No_Block")]
    for u, (cat, pos, block) in data.items():
        if cat not in ("CM", "SM", "RS", "H", "M", "MPst"):
            pos = "END"
        if cat in ("C", "CS", "Ra", "CM", "V", "PLACEHOLDER", "DOTTEDCIRCLE"):
            pos = "BASE_C"
        elif cat in ("M", "MPst"):
            pos = matra_position(u, pos, block)
        elif cat in ("SM", "SMPst", "VD", "A", "Symbol"):
            pos = "SMVD"
        data[u] = [cat, pos, block]
    for u, pos in POSITION_OVERRIDES.items():
        data[u][1] = pos

    # Ranges of equal (category, position); code points not listed are X/END.
    starts, values, previous = [], [], None
    for u in range(0, max(data) + 2):
        cat, pos, _ = data.get(u, ["X", "END", ""])
        value = CATEGORIES.index(cat) | POSITIONS.index(pos) << 8
        if value != previous:
            starts.append(u)
            values.append(value)
            previous = value

    out = [HEADER.format(version=VERSION), "namespace DotOffice.Fonts.Shaping;\n\n",
           "internal static class IndicData\n{\n",
           "    /// <summary>First code point of each range; a range extends to the next start.</summary>\n",
           "    public static ReadOnlySpan<int> RangeStarts => new int[]\n    {\n"]
    out += wrap([f"0x{u:X}" for u in starts])
    out += ["    };\n\n",
            "    /// <summary>Per range: <see cref=\"IndicCategory\"/> in the low byte, <see cref=\"IndicPosition\"/> in the next.</summary>\n",
            "    public static ReadOnlySpan<ushort> RangeValues => new ushort[]\n    {\n"]
    out += wrap([f"0x{v:X}" for v in values])
    out += ["    };\n}\n"]
    path = os.path.join(ROOT, "src/DotOffice.Fonts/Shaping/IndicData.g.cs")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(out))
    print(f"wrote {path}: {len(starts)} ranges")


def wrap(items, per_line=12):
    return ["        " + ", ".join(items[i:i + per_line]) + ",\n" for i in range(0, len(items), per_line)]


if __name__ == "__main__":
    main()
