#!/usr/bin/env python3
"""Generates src/DotOffice.Fonts/Shaping/ScriptData.g.cs: the Unicode Script property (Scripts.txt) as used by
LibreOffice's ScriptRun to split text before shaping, with LibreOffice's adjustments baked in (non-spacing marks
are Inherited, Katakana is Hiragana), and the OpenType script tag of each script (HarfBuzz's old-style tags).

Usage: python3 tools/generate-script-data.py [directory containing the UCD files]
Without an argument the files are downloaded from unicode.org (version below).
"""
import os, sys, urllib.request

VERSION = "16.0.0"
BASE = f"https://www.unicode.org/Public/{VERSION}/ucd/"
FILES = ("Scripts.txt", "PropertyValueAliases.txt", "UnicodeData.txt")

ROOT = os.path.join(os.path.dirname(__file__), "..")
# HarfBuzz's hb_ot_old_tag_from_script exceptions; other tags are the ISO 15924 code in lower case.
TAG_EXCEPTIONS = {"Hira": "kana", "Laoo": "lao ", "Yiii": "yi  ", "Nkoo": "nko ", "Vaii": "vai "}


def load(name):
    if len(sys.argv) > 1:
        return open(os.path.join(sys.argv[1], name), encoding="utf-8").read()
    return urllib.request.urlopen(BASE + name).read().decode("utf-8")


def ranges(text):
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        fields = [p.strip() for p in line.split(";")]
        lo, _, hi = fields[0].partition("..")
        yield int(lo, 16), int(hi or lo, 16), fields[1:]


def main():
    codes = {}
    for line in load("PropertyValueAliases.txt").splitlines():
        parts = [p.strip() for p in line.split("#", 1)[0].split(";")]
        if len(parts) >= 3 and parts[0] == "sc":
            codes[parts[2]] = parts[1]

    # 0 Common, 1 Inherited, 2 Unknown, then every other script; sameScript treats indices <= 1 as wildcards.
    names = ["Zyyy", "Zinh", "Zzzz"] + sorted(c for c in codes.values() if c not in ("Zyyy", "Zinh", "Zzzz", "Kana", "Hrkt"))
    index = {c: i for i, c in enumerate(names)}
    index["Kana"] = index["Hrkt"] = index["Hira"]
    assert len(names) < 256

    scripts = bytearray([index["Zzzz"]]) * 0x110000
    for lo, hi, (name,) in ranges(load("Scripts.txt")):
        scripts[lo:hi + 1] = bytes([index[codes[name]]]) * (hi - lo + 1)

    # Non-spacing marks inherit the script of their base (LibreOffice tdf#154549).
    first = None
    for line in load("UnicodeData.txt").splitlines():
        fields = line.split(";")
        cp = int(fields[0], 16)
        if fields[1].endswith(", First>"):
            first = cp
            continue
        lo = first if fields[1].endswith(", Last>") else cp
        first = None
        if fields[2] == "Mn":
            scripts[lo:cp + 1] = bytes([index["Zinh"]]) * (cp - lo + 1)

    starts, values = [], []
    for cp in range(0x110000):
        if not values or scripts[cp] != values[-1]:
            starts.append(cp); values.append(scripts[cp])

    tags = ["DFLT", "DFLT", "DFLT"] + [TAG_EXCEPTIONS.get(c, c[0].lower() + c[1:]) for c in names[3:]]
    out = os.path.join(ROOT, "src", "DotOffice.Fonts", "Shaping", "ScriptData.g.cs")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// <auto-generated>\n")
        f.write(f"// Generated by tools/generate-script-data.py from the Unicode Character Database {VERSION}.\n")
        f.write("// Unicode Character Database: Copyright (c) 1991-2024 Unicode, Inc.\n")
        f.write("// Distributed under the Unicode License v3; see THIRD-PARTY-NOTICES.md.\n")
        f.write("// </auto-generated>\n\nnamespace DotOffice.Fonts.Shaping;\n\n")
        f.write("internal static class ScriptData\n{\n")
        f.write("    public const byte Common = 0, Inherited = 1;\n\n")
        f.write("    /// <summary>OpenType script tag of each script index (DFLT for Common, Inherited and Unknown).</summary>\n")
        f.write("    public static readonly string[] Tags =\n    [\n")
        for i in range(0, len(tags), 12):
            f.write("        " + ", ".join(f'"{t}"' for t in tags[i:i + 12]) + ",\n")
        f.write("    ];\n\n")
        f.write("    /// <summary>First code point of each range; a range extends to the next start.</summary>\n")
        f.write("    public static ReadOnlySpan<int> RangeStarts => new int[]\n    {\n")
        for i in range(0, len(starts), 12):
            f.write("        " + ", ".join(f"0x{s:X}" for s in starts[i:i + 12]) + ",\n")
        f.write("    };\n\n")
        f.write("    /// <summary>Script index of each range.</summary>\n")
        f.write("    public static ReadOnlySpan<byte> RangeScripts =>\n    [\n")
        for i in range(0, len(values), 24):
            f.write("        " + ", ".join(str(v) for v in values[i:i + 24]) + ",\n")
        f.write("    ];\n}\n")
    print(f"{len(starts)} ranges, {len(names)} scripts written to {os.path.normpath(out)}")


if __name__ == "__main__":
    main()
